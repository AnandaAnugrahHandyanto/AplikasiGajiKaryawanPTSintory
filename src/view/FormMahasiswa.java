    private void hitungButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_hitungButtonActionPerformed
        try {
        String nim = nimTextField.getText().trim();
        String nama = namaTextField.getText().trim();
        
        if (nim.isEmpty() || nama.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, 
                "NIM dan Nama harus diisi!");
            return;
        }
        
        String jenisKelamin = "";
        if (lakiRadioButton.isSelected()) jenisKelamin = "Laki-laki";
        else if (perempuanRadioButton.isSelected()) jenisKelamin = "Perempuan";
        else {
            javax.swing.JOptionPane.showMessageDialog(this, 
                "Pilih Jenis Kelamin!");
            return;
        }
        
        String jurusan = jurusanComboBox.getSelectedItem().toString();
        
        int semester = Integer.parseInt(semesterTextField.getText().trim());
        double biaya = Double.parseDouble(biayaTextField.getText().trim());
        
        double kehadiran = Double.parseDouble(nilaiKehadiranTextField.getText().trim());
        double tugas = Double.parseDouble(nilaiTugasTextField.getText().trim());
        double uts = Double.parseDouble(nilaiUTSTextField.getText().trim());
        double uas = Double.parseDouble(nilaiUASTextField.getText().trim());
        
        model.Mahasiswa mhs = new model.Mahasiswa(
            nim, nama, jenisKelamin, jurusan, semester, biaya,
            kehadiran, tugas, uts, uas
        );
        
        nilaiPemrogramanTextField.setText(
            String.format("%.2f", mhs.getNilaiPemrograman()));
        gradeTextField.setText(mhs.getGrade());
        
        outputTextArea.setText("");
        outputTextArea.append("=== DATA MAHASISWA ===\n");
        outputTextArea.append("NIM            : " + mhs.getNim() + "\n");
        outputTextArea.append("Nama           : " + mhs.getNama() + "\n");
        outputTextArea.append("Jenis Kelamin  : " + mhs.getJenisKelamin() + "\n");
        outputTextArea.append("Jurusan        : " + mhs.getJurusan() + "\n");
        outputTextArea.append("Semester       : " + mhs.getSemester() + "\n");
        outputTextArea.append("Biaya/bln      : Rp " + mhs.getBiaya() + "\n");
        outputTextArea.append("-----------------------------------\n");
        outputTextArea.append("Nilai Kehadiran: " + mhs.getNilaiKehadiran() + "\n");
        outputTextArea.append("Nilai Tugas    : " + mhs.getNilaiTugas() + "\n");
        outputTextArea.append("Nilai UTS      : " + mhs.getNilaiUTS() + "\n");
        outputTextArea.append("Nilai UAS      : " + mhs.getNilaiUAS() + "\n");
        outputTextArea.append("Nilai Akhir    : " + 
            String.format("%.2f", mhs.getNilaiPemrograman()) + "\n");
        outputTextArea.append("Grade          : " + mhs.getGrade() + "\n");
        
    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this, 
            "Pastikan semua input angka sudah benar!");
    }
    }//GEN-LAST:event_hitungButtonActionPerformed

