    private void bayarButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bayarButtonActionPerformed
    try {
            String noMeja = noMejaTextField.getText().trim();
            if (noMeja.isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(this, 
                    "No. Meja harus diisi!");
                return;
            }

            double totalPesanan = Double.parseDouble(totalPesananTextField.getText().trim());
            double uangPembayaran = Double.parseDouble(uangPembayaranTextField.getText().trim());

            double ppn = 0.1 * totalPesanan;
            double totalBayar = totalPesanan + ppn;

            if (uangPembayaran < totalBayar) {
                javax.swing.JOptionPane.showMessageDialog(this, 
                    "Uang pembayaran kurang!\nTotal bayar: Rp " + totalBayar);
                return;
            }

            double uangKembali = uangPembayaran - totalBayar;

            ppnTextField.setText(String.format("%.0f", ppn));
            uangKembaliTextField.setText(String.format("%.0f", uangKembali));

            strukTextArea.setText("");
            strukTextArea.append("=== STRUK PEMBAYARAN ===\n");
            strukTextArea.append("No. Meja       : " + noMeja + "\n");
            strukTextArea.append("---------------------------------\n");
            strukTextArea.append("Total Pesanan  : Rp " + String.format("%.0f", totalPesanan) + "\n");
            strukTextArea.append("PPN (10%)      : Rp " + String.format("%.0f", ppn) + "\n");
            strukTextArea.append("Total Bayar    : Rp " + String.format("%.0f", totalBayar) + "\n");
            strukTextArea.append("---------------------------------\n");
            strukTextArea.append("Uang Bayar     : Rp " + String.format("%.0f", uangPembayaran) + "\n");
            strukTextArea.append("Uang Kembali   : Rp " + String.format("%.0f", uangKembali) + "\n");
            strukTextArea.append("=================================\n");

            javax.swing.table.DefaultTableModel model = 
                (javax.swing.table.DefaultTableModel) transaksiTable.getModel();
            model.addRow(new Object[]{
                noMeja,
                String.format("%.0f", totalPesanan),
                String.format("%.0f", ppn),
                String.format("%.0f", totalBayar)
            });

            double totalPendapatan = 0;
            for (int i = 0; i < model.getRowCount(); i++) {
                totalPendapatan += Double.parseDouble(model.getValueAt(i, 3).toString());
            }
            totalPendapatanTextField.setText(String.format("%.0f", totalPendapatan));

            totalPesananTextField.setText("");
            uangPembayaranTextField.setText("");

        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, 
                "Pastikan input angka sudah benar!");
        }
    }//GEN-LAST:event_bayarButtonActionPerformed

